#!/usr/bin/env python3
"""Static contract tests between the iOS client and the Cloudflare Worker.

The iOS build repository holds the app source only, so the Worker surface it
depends on is checked in as `tests/fixtures/worker_contract.json`, generated by
`tools/export_worker_contract.py` from the real `worker.js`. In the full
workspace the fixture is also re-derived and compared, so a route rename cannot
drift unnoticed.

Nothing here touches the network or a KEY, so it runs on the Windows development
box that has no Swift toolchain.
"""

from __future__ import annotations

import importlib.util
import json
import re
import unittest
from pathlib import Path

SOURCE_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = SOURCE_ROOT.parent
WORKER = REPO_ROOT / "REDESIGN_V2" / "worker" / "worker.js"
FIXTURE = SOURCE_ROOT / "tests" / "fixtures" / "worker_contract.json"
APP_DIR = SOURCE_ROOT / "NBTAimlock"
VIEWS_DIR = APP_DIR / "Views"
TOOLS_ROOT = SOURCE_ROOT / "tools"

# What the client parses out of each response. Kept here, not in the exporter,
# so a field silently dropped from Worker and fixture together still fails.
EXPECTED_FIELDS = {
    "/api/license/authorize": {"featureId", "nonce", "expiresAt", "signature"},
    "/api/lockout-status": {"isLockedOut", "failedCount", "remainingSeconds", "maxAttempts"},
    "/api/legal": {"found", "doc", "type"},
    "/api/sensitivity": {"presets", "light", "mid", "heavy"},
    "/api/config": {"features"},
    "/api/announcement": {"announcements"},
}


def load_tool(name: str):
    path = TOOLS_ROOT / name
    spec = importlib.util.spec_from_file_location(name.replace(".py", ""), path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def read_fixture() -> dict:
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


class EndpointContractTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tool = load_tool("obfuscate_strings.py")
        cls.contract = read_fixture()
        cls.routes = set(cls.contract["routes"])

    def test_every_endpoint_the_app_calls_exists_on_the_worker(self):
        endpoints = [text for _, text in self.tool.STRINGS if text.startswith("/api/")]
        self.assertGreaterEqual(len(endpoints), 9, endpoints)
        for endpoint in endpoints:
            with self.subTest(endpoint=endpoint):
                self.assertIn(endpoint, self.routes)

    def test_feature_roster_matches_the_worker(self):
        swift = (APP_DIR / "Config" / "NABATIAppConfig.swift").read_text(encoding="utf-8")
        ios_ids = set(re.findall(r'NABATIFeature\(id: "([a-z0-9_]+)"', swift))
        worker_ids = set(self.contract["featureIds"])
        self.assertEqual(len(ios_ids), 8, ios_ids)
        self.assertEqual(ios_ids, worker_ids)

    def test_fixture_is_current_with_worker_js(self):
        if not WORKER.is_file():
            self.skipTest("worker.js is not part of this repository")
        exporter = load_tool("export_worker_contract.py")
        self.assertEqual(exporter.build_contract(), self.contract)


class ResponseShapeTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.fields = read_fixture()["responseFields"]

    def test_documented_fields_are_still_present(self):
        for route, required in EXPECTED_FIELDS.items():
            with self.subTest(route=route):
                actual = set(self.fields.get(route, []))
                self.assertTrue(
                    required.issubset(actual),
                    "missing %s in %s" % (sorted(required - actual), route),
                )

    def test_legal_documents_keep_the_schema_the_reader_parses(self):
        # The document itself is JSON stored by the Admin writer, so its keys
        # are checked there rather than in the read route.
        stored = set(read_fixture()["legalDocFields"])
        required = {"title", "content", "updated_label", "contact"}
        self.assertTrue(required.issubset(stored), sorted(required - stored))

    def test_every_route_under_test_is_real(self):
        routes = set(read_fixture()["routes"])
        for route in EXPECTED_FIELDS:
            self.assertIn(route, routes)


def button_action_bodies(source: str):
    """Yield the text inside every `Button(action: { ... })` closure.

    Tracks brace depth and skips string literals so a `}` inside a label cannot
    end the body early.
    """
    needle = "Button(action:"
    index = 0
    while True:
        start = source.find(needle, index)
        if start < 0:
            return
        brace = source.find("{", start + len(needle))
        if brace < 0:
            return
        depth = 0
        in_string = False
        escaped = False
        i = brace
        while i < len(source):
            char = source[i]
            if in_string:
                if escaped:
                    escaped = False
                elif char == chr(92):
                    escaped = True
                elif char == '"':
                    in_string = False
            elif char == '"':
                in_string = True
            elif char == "{":
                depth += 1
            elif char == "}":
                depth -= 1
                if depth == 0:
                    yield source[brace + 1:i]
                    index = i + 1
                    break
            i += 1
        else:
            return


class NoFakeButtonTests(unittest.TestCase):
    """Rule 3: a control on screen must reach the server, not just change state."""

    @classmethod
    def setUpClass(cls):
        cls.sources = {
            path.name: path.read_text(encoding="utf-8")
            for path in sorted(VIEWS_DIR.glob("*.swift"))
        }

    def test_no_empty_button_actions(self):
        checked = 0
        for name, source in self.sources.items():
            for body in button_action_bodies(source):
                checked += 1
                with self.subTest(file=name, body=body.strip()[:60]):
                    self.assertTrue(body.strip(), "empty Button(action:) in %s" % name)
        self.assertGreater(checked, 25, "expected a substantial number of buttons")

    def test_feature_switches_call_the_store(self):
        dashboard = (VIEWS_DIR / "AimlockDashboardView.swift").read_text(encoding="utf-8")
        self.assertIn("store.toggle(featureId:", dashboard)
        self.assertNotIn("@State private var isOn", dashboard)


if __name__ == "__main__":
    unittest.main()
